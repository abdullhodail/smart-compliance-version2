export function getQuestionLabel(question: PDPLQuestion, entityType: EntityType, businessActivity?: string | null): string {
  if (entityType === "SME" && businessActivity && question.labels.SME_PERSONALIZED?.[businessActivity]) {
    return question.labels.SME_PERSONALIZED[businessActivity];
  }
  return question.labels[entityType];
}
